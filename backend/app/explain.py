"""Explanations built only from computed route attributes. No text here is
generated by a language model, and no number is invented."""
from __future__ import annotations

import numpy as np

from .profiles import Profile
from .terrain import Terrain

LABEL = {"shortest": "Shortest", "safest": "Safest", "optimal": "Optimal"}


def _fmt_dur(seconds: float) -> str:
    m = int(round(seconds / 60.0))
    return f"{m // 60} h {m % 60:02d} min" if m >= 60 else f"{m} min"


def _pct(new: float, old: float) -> str:
    if old <= 1e-9:
        return "n/a"
    return f"{100.0 * (new - old) / old:+.0f}%"


def _deviation(terrain: Terrain, a: dict, b: dict) -> dict | None:
    """Where route ``b`` departs furthest from route ``a``, and what ``a``
    crosses around that place."""
    pa, pb = np.asarray(a["path"], dtype=float), np.asarray(b["path"], dtype=float)
    d = np.hypot(pa[:, None, 0] - pb[None, :, 0], pa[:, None, 1] - pb[None, :, 1])
    nearest = d.min(axis=1)
    i = int(nearest.argmax())
    sep_m = float(nearest[i] * terrain.cell_size)
    if sep_m < 2.5 * terrain.cell_size:
        return None
    apart = np.where(nearest > 1.5)[0]
    lo, hi = int(apart.min()), int(apart.max())
    j_lo, j_hi = sorted((int(d[lo].argmin()), int(d[hi].argmin())))
    j_hi = max(j_hi, j_lo + 1)
    return {
        "sep_m": sep_m,
        "from_m": a["profile"]["dist"][lo],
        "to_m": a["profile"]["dist"][hi],
        "a_max_slope": max(a["profile"]["slope"][lo:hi + 1]),
        "a_max_risk": max(a["profile"]["risk"][lo:hi + 1]),
        "a_min_conf": min(a["profile"]["conf"][lo:hi + 1]),
        "b_max_slope": max(b["profile"]["slope"][j_lo:j_hi + 1]),
        "b_max_risk": max(b["profile"]["risk"][j_lo:j_hi + 1]),
        "b_min_conf": min(b["profile"]["conf"][j_lo:j_hi + 1]),
    }


def _compare(terrain: Terrain, base_key: str, base: dict, key: str, other: dict) -> str:
    mb, mo = base["metrics"], other["metrics"]
    if base["path"] == other["path"]:
        return (f"The {LABEL[key].lower()} route is identical to the {LABEL[base_key].lower()} route: under the "
                f"current model no alternative scores better on its objective.")
    extra = mo["distance_m"] - mb["distance_m"]
    parts = [
        f"The {LABEL[key].lower()} route is {abs(extra):.0f} m {'longer' if extra >= 0 else 'shorter'} than the "
        f"{LABEL[base_key].lower()} route ({_pct(mo['distance_m'], mb['distance_m'])}).",
        f"Hazard exposure changes from {mb['hazard_exposure']:.2f} to {mo['hazard_exposure']:.2f} "
        f"({_pct(mo['hazard_exposure'], mb['hazard_exposure'])}), the steepest cell on the route from "
        f"{mb['max_slope_deg']:.1f} deg to {mo['max_slope_deg']:.1f} deg, and energy use from "
        f"{mb['energy_wh']:.0f} Wh to {mo['energy_wh']:.0f} Wh.",
    ]
    dev = _deviation(terrain, base, other)
    if dev:
        why = []
        if dev["a_max_slope"] - dev["b_max_slope"] > 1.0:
            why.append(f"slopes up to {dev['a_max_slope']:.1f} deg (the alternative stays at or below {dev['b_max_slope']:.1f} deg there)")
        if dev["a_max_risk"] - dev["b_max_risk"] > 0.05:
            why.append(f"risk up to {dev['a_max_risk']:.2f} (versus {dev['b_max_risk']:.2f})")
        if dev["b_min_conf"] - dev["a_min_conf"] > 0.1:
            why.append(f"terrain mapped with confidence as low as {dev['a_min_conf']:.2f} (versus {dev['b_min_conf']:.2f})")
        seg = (f"Largest detour: between {dev['from_m']:.0f} m and {dev['to_m']:.0f} m along the "
               f"{LABEL[base_key].lower()} route the two paths separate by up to {dev['sep_m']:.0f} m.")
        if why:
            seg += f" On that stretch the {LABEL[base_key].lower()} route crosses " + "; ".join(why) + "."
        parts.append(seg)
    return " ".join(parts)


def explain(terrain: Terrain, p: Profile, routes: dict, weights: dict) -> list[dict]:
    out: list[dict] = []
    ok = {k: r for k, r in routes.items() if r.get("status") == "ok"}
    if not ok:
        reason = next(iter(routes.values())).get("reason", "No route found.")
        return [{"title": "No route available", "kind": "warning", "text": reason}]

    s, f, o = ok.get("shortest"), ok.get("safest"), ok.get("optimal")
    if s and f:
        out.append({"title": "Why is the safest route different?", "kind": "info", "text": _compare(terrain, "shortest", s, "safest", f)})
    if s and o:
        w = ", ".join(f"{k} {100 * v:.0f}%" for k, v in weights.items())
        text = _compare(terrain, "shortest", s, "optimal", o)
        if o["metrics"]["science_sites"]:
            text += " It passes within 60 m of: " + ", ".join(o["metrics"]["science_sites"]) + "."
        out.append({"title": "Why this optimal route?", "kind": "info", "text": f"Current priorities: {w}. {text}"})

    cheapest = min(ok, key=lambda k: ok[k]["metrics"]["energy_wh"])
    fastest = min(ok, key=lambda k: ok[k]["metrics"]["duration_s"])
    out.append({
        "title": "Energy and time", "kind": "info",
        "text": f"Lowest energy: {LABEL[cheapest].lower()} route ({ok[cheapest]['metrics']['energy_wh']:.0f} Wh). "
                f"Fastest: {LABEL[fastest].lower()} route ({_fmt_dur(ok[fastest]['metrics']['duration_s'])}). "
                f"Usable budget for this profile is {ok[cheapest]['metrics']['energy_usable_wh']:.0f} Wh "
                f"({p.capacity_wh:.0f} Wh minus a {100 * p.reserve_frac:.0f}% reserve).",
    })
    bad = [LABEL[k] for k, r in ok.items() if not r["metrics"]["energy_feasible"]]
    if bad:
        out.append({"title": "Energy budget exceeded", "kind": "warning",
                    "text": f"Not feasible on energy under the current assumptions: {', '.join(bad)}. "
                            f"The required energy exceeds the usable budget, so the reserve would be consumed."})
    low = [LABEL[k] for k, r in ok.items() if r["metrics"]["min_confidence"] < 0.35]
    if low:
        out.append({"title": "Poorly mapped terrain on route", "kind": "warning",
                    "text": f"{', '.join(low)} cross cells where terrain confidence is below 0.35. Low confidence "
                            f"means the terrain is not well known; it is not evidence that it is safe."})
    return out
